"""Reproducible load test for OctoScale.

Scenarios (in order):
  1. setup     create --urls short links and warm the redirect cache (not measured)
  2. redirect  sustained GET /{code} for --duration seconds, spread across --clients simulated clients
  3. create    sustained POST /api/v1/shorten for --create-duration seconds with unique URLs
  4. limiter   a burst of 3x the limit from ONE client against each rate-limited route, to check that
               exactly `limit` requests are allowed and the rest get 429 with Retry-After

Simulated clients are distinct X-Forwarded-For addresses, so the server must run with
TRUST_PROXY_HEADERS=true (as it would behind a load balancer). Traffic is generated by --processes
worker processes, each running --concurrency / --processes async connections, so the Python client
is less likely to be the bottleneck. Every number lands in the JSON written to --output.

Example:
  python benchmarks/load_test.py --base-url http://127.0.0.1:8000 --duration 30 --concurrency 128 \
      --processes 4 --output benchmarks/results.json
"""

from __future__ import annotations

import argparse
import asyncio
import json
import math
import multiprocessing as mp
import os
import platform
import random
import statistics
import subprocess
import sys
import time
import uuid
from collections import Counter
from datetime import datetime, timezone

import httpx

try:
    import psutil
except ImportError:  # metadata only
    psutil = None


# ---------------------------------------------------------------- helpers


def client_ip(n: int) -> str:
    return f"10.{(n >> 16) & 255}.{(n >> 8) & 255}.{n & 255}"


def percentile(sorted_values: list[float], q: float) -> float:
    """Nearest-rank percentile."""
    if not sorted_values:
        return float("nan")
    k = max(0, min(len(sorted_values) - 1, math.ceil(q / 100 * len(sorted_values)) - 1))
    return sorted_values[k]


def summarize(latencies_ms: list[float], statuses: Counter, errors: int, elapsed_s: float, expected: set[int]) -> dict:
    lat = sorted(latencies_ms)
    total = sum(statuses.values()) + errors
    unexpected = sum(n for code, n in statuses.items() if code not in expected) + errors
    return {
        "requests": total,
        "duration_s": round(elapsed_s, 3),
        "requests_per_second": round(total / elapsed_s, 1) if elapsed_s else 0.0,
        "latency_ms": {
            "p50_ms": round(percentile(lat, 50), 3),
            "p95_ms": round(percentile(lat, 95), 3),
            "p99_ms": round(percentile(lat, 99), 3),
            "max_ms": round(lat[-1], 3) if lat else None,
            "mean_ms": round(statistics.fmean(lat), 3) if lat else None,
        },
        "status_counts": {str(k): v for k, v in sorted(statuses.items())},
        "transport_errors": errors,
        "error_rate": round(unexpected / total, 6) if total else 0.0,
        "expected_statuses": sorted(expected),
    }


KEEPALIVE_EXPIRY_S = 2.0  # below uvicorn's 5 s keep-alive timeout, so the client never reuses a socket the server is closing


def make_client(base_url: str, connections: int) -> httpx.AsyncClient:
    limits = httpx.Limits(max_connections=connections, max_keepalive_connections=connections, keepalive_expiry=KEEPALIVE_EXPIRY_S)
    return httpx.AsyncClient(base_url=base_url, limits=limits, timeout=httpx.Timeout(10.0), follow_redirects=False)


# ---------------------------------------------------------------- traffic workers (run in subprocesses)


async def _drive(base_url: str, kind: str, payload: dict, concurrency: int, duration: float, seed: int) -> dict:
    rnd = random.Random(seed)
    codes: list[str] = payload.get("codes", [])
    n_clients: int = payload["clients"]
    latencies: list[float] = []
    statuses: Counter = Counter()
    error_types: Counter = Counter()
    errors = 0
    deadline = time.perf_counter() + duration

    async with make_client(base_url, concurrency) as client:

        async def worker(wid: int) -> None:
            nonlocal errors
            i = 0
            while time.perf_counter() < deadline:
                ip = client_ip(rnd.randrange(n_clients))
                start = time.perf_counter()
                try:
                    if kind == "redirect":
                        r = await client.get(f"/{rnd.choice(codes)}", headers={"X-Forwarded-For": ip})
                    else:
                        url = f"https://bench.example/{seed}/{wid}/{i}/{uuid.uuid4().hex[:8]}"
                        r = await client.post("/api/v1/shorten", json={"original_url": url}, headers={"X-Forwarded-For": ip})
                    latencies.append((time.perf_counter() - start) * 1000)
                    statuses[r.status_code] += 1
                except httpx.HTTPError as exc:
                    errors += 1
                    error_types[type(exc).__name__] += 1
                i += 1

        started = time.perf_counter()
        await asyncio.gather(*(worker(w) for w in range(concurrency)))
        elapsed = time.perf_counter() - started

    return {"latencies": latencies, "statuses": dict(statuses), "errors": errors, "error_types": dict(error_types), "elapsed": elapsed}


def _process_entry(args: tuple) -> dict:
    base_url, kind, payload, concurrency, duration, seed = args
    return asyncio.run(_drive(base_url, kind, payload, concurrency, duration, seed))


def run_phase(base_url: str, kind: str, payload: dict, concurrency: int, processes: int, duration: float, expected: set[int]) -> dict:
    per_proc = max(1, concurrency // processes)
    kind_seed = {"redirect": 1, "create": 2}[kind]
    jobs = [(base_url, kind, payload, per_proc, duration, 1000 * (p + 1) + kind_seed) for p in range(processes)]
    wall_start = time.perf_counter()
    with mp.get_context("spawn").Pool(processes) as pool:
        parts = pool.map(_process_entry, jobs)
    wall = time.perf_counter() - wall_start
    latencies = [x for part in parts for x in part["latencies"]]
    statuses: Counter = Counter()
    for part in parts:
        statuses.update({int(k): v for k, v in part["statuses"].items()})
    errors = sum(part["errors"] for part in parts)
    error_types: Counter = Counter()
    for part in parts:
        error_types.update(part["error_types"])
    elapsed = max(part["elapsed"] for part in parts)
    result = summarize(latencies, statuses, errors, elapsed, expected)
    result["transport_error_types"] = dict(error_types)
    result["concurrency"] = per_proc * processes
    result["processes"] = processes
    result["wall_clock_s_including_process_start"] = round(wall, 3)
    return result


# ---------------------------------------------------------------- setup and limiter checks (main process)


async def setup_urls(base_url: str, n: int) -> tuple[list[str], int]:
    """Create n links, then warm the cache with one redirect each. Returns (codes, warm-up 307 count)."""
    codes: list[str] = []
    warm_redirects = 0
    sem = asyncio.Semaphore(32)
    async with make_client(base_url, 32) as client:

        async def create(i: int) -> None:
            async with sem:
                r = await client.post(
                    "/api/v1/shorten",
                    json={"original_url": f"https://setup.example/{uuid.uuid4().hex}/{i}"},
                    headers={"X-Forwarded-For": client_ip(50_000 + i)},
                )
                r.raise_for_status()
                codes.append(r.json()["short_code"])

        await asyncio.gather(*(create(i) for i in range(n)))
        # Warm the cache and connection pools; not measured.
        for i, code in enumerate(codes):
            r = await client.get(f"/{code}", headers={"X-Forwarded-For": client_ip(70_000 + i)})
            warm_redirects += r.status_code == 307
    return codes, warm_redirects


# ---------------------------------------------------------------- data integrity (optional, needs DB access)


async def db_counts(db_url: str) -> dict:
    from sqlalchemy import text
    from sqlalchemy.ext.asyncio import create_async_engine

    engine = create_async_engine(db_url)
    try:
        async with engine.connect() as conn:
            row = (await conn.execute(text(
                "SELECT (SELECT count(*) FROM urls), (SELECT count(DISTINCT short_code) FROM urls), "
                "(SELECT count(*) FROM click_analytics), (SELECT coalesce(sum(clicks), 0) FROM urls)"
            ))).one()
    finally:
        await engine.dispose()
    return {"url_rows": row[0], "distinct_short_codes": row[1], "click_rows": row[2], "click_counter_sum": int(row[3])}


async def wait_for_clicks(db_url: str, expected_click_rows: int, timeout_s: float = 60) -> dict:
    """Clicks are written asynchronously in batches; wait until the expected rows land or stop growing."""
    deadline = time.perf_counter() + timeout_s
    last, stable = None, 0
    while True:
        counts = await db_counts(db_url)
        if counts["click_rows"] >= expected_click_rows or time.perf_counter() > deadline:
            return counts
        stable = stable + 1 if counts == last else 0
        if stable >= 5:
            return counts
        last = counts
        await asyncio.sleep(1)


async def limiter_burst(base_url: str, route: str, code: str, limit: int, concurrency: int) -> dict:
    """Send 3x `limit` requests from one fresh client as fast as possible."""
    ip = f"172.31.{random.randrange(256)}.{random.randrange(1, 255)}"
    sent = limit * 3
    statuses: Counter = Counter()
    retry_after_ok = 0
    backends: Counter = Counter()
    sem = asyncio.Semaphore(concurrency)
    async with make_client(base_url, concurrency) as client:

        async def one(i: int) -> None:
            nonlocal retry_after_ok
            async with sem:
                if route == "redirect":
                    r = await client.get(f"/{code}", headers={"X-Forwarded-For": ip})
                else:
                    r = await client.post(
                        "/api/v1/shorten",
                        json={"original_url": f"https://limit.example/{uuid.uuid4().hex}/{i}"},
                        headers={"X-Forwarded-For": ip},
                    )
                statuses[r.status_code] += 1
                backends[r.headers.get("x-ratelimit-backend", "none")] += 1
                if r.status_code == 429 and r.headers.get("retry-after", "").isdigit():
                    retry_after_ok += 1

        start = time.perf_counter()
        await asyncio.gather(*(one(i) for i in range(sent)))
        elapsed = time.perf_counter() - start

    allowed = sum(n for s, n in statuses.items() if s < 400)
    rejected = statuses.get(429, 0)
    return {
        "route": route,
        "limit_per_window": limit,
        "requests_sent": sent,
        "allowed": allowed,
        "rejected_429": rejected,
        "other_statuses": {str(s): n for s, n in statuses.items() if s >= 400 and s != 429},
        "accuracy": round(allowed / limit, 4),
        "exact": allowed == limit,
        "429_with_retry_after": retry_after_ok,
        "limiter_backend": dict(backends),
        "burst_duration_s": round(elapsed, 3),
    }


# ---------------------------------------------------------------- metadata


def environment(args: argparse.Namespace, health: dict | None, redis_version: str | None) -> dict:
    env = {
        "os": platform.platform(),
        "cpu_model": platform.processor(),
        "cpu_logical_cores": os.cpu_count(),
        "python": sys.version.split()[0],
        "httpx": httpx.__version__,
        "client_and_server_on_same_host": args.same_host,
    }
    if psutil:
        env["cpu_physical_cores"] = psutil.cpu_count(logical=False)
        env["memory_gb"] = round(psutil.virtual_memory().total / 2**30, 1)
    if sys.platform == "win32":
        try:
            name = subprocess.run(
                ["powershell", "-NoProfile", "-Command", "(Get-CimInstance Win32_Processor | Select -First 1).Name"],
                capture_output=True, text=True, timeout=10,
            ).stdout.strip()
            if name:
                env["cpu_model"] = name
        except Exception:
            pass
    env["server"] = {
        "workers": args.server_workers,
        "database": args.database,
        "redis_version": redis_version,
        "notes": args.notes,
        "health": health,
    }
    return env


def git_commit() -> str | None:
    try:
        return subprocess.run(["git", "rev-parse", "--short", "HEAD"], capture_output=True, text=True, timeout=5).stdout.strip() or None
    except Exception:
        return None


# ---------------------------------------------------------------- main


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--base-url", default="http://127.0.0.1:8000")
    p.add_argument("--duration", type=float, default=30, help="seconds of sustained redirect traffic")
    p.add_argument("--create-duration", type=float, default=15, help="seconds of sustained create traffic")
    p.add_argument("--concurrency", type=int, default=128, help="total concurrent connections")
    p.add_argument("--processes", type=int, default=4, help="load-generator processes")
    p.add_argument("--clients", type=int, default=20_000, help="simulated client IPs (X-Forwarded-For)")
    p.add_argument("--urls", type=int, default=1000, help="short links created during setup")
    p.add_argument("--redirect-limit", type=int, default=600, help="server REDIRECT_RATE_LIMIT_PER_MINUTE")
    p.add_argument("--api-limit", type=int, default=100, help="server RATE_LIMIT_PER_MINUTE")
    p.add_argument("--server-workers", type=int, default=None, help="recorded in metadata")
    p.add_argument("--database", default=None, help="recorded in metadata, e.g. 'sqlite (WAL)' or 'postgres 16'")
    p.add_argument("--redis-url", default=None, help="optional: read the Redis server version for metadata")
    p.add_argument("--notes", default=None)
    p.add_argument("--same-host", action="store_true", help="load generator and server share the machine")
    p.add_argument("--verify-db-url", default=None,
                   help="optional SQLAlchemy async URL of the server's database; checks every 201 became a URL row "
                        "and every 307 became a click row")
    p.add_argument("--output", default="benchmarks/results.json")
    args = p.parse_args()

    started_at = datetime.now(timezone.utc).isoformat(timespec="seconds")
    health = httpx.get(f"{args.base_url}/api/v1/health", timeout=5).json()
    redis_version = None
    if args.redis_url:
        import redis

        redis_version = redis.Redis.from_url(args.redis_url, protocol=2).info("server").get("redis_version")
    before = asyncio.run(db_counts(args.verify_db_url)) if args.verify_db_url else None

    print(f"setup: creating {args.urls} links ...", flush=True)
    codes, warm_redirects = asyncio.run(setup_urls(args.base_url, args.urls))

    print(f"redirect: {args.duration}s at concurrency {args.concurrency} ...", flush=True)
    redirect = run_phase(args.base_url, "redirect", {"codes": codes, "clients": args.clients},
                         args.concurrency, args.processes, args.duration, {307})

    print(f"create: {args.create_duration}s at concurrency {args.concurrency} ...", flush=True)
    create = run_phase(args.base_url, "create", {"clients": args.clients},
                       args.concurrency, args.processes, args.create_duration, {201})

    print("limiter: bursts of 3x the limit from one client ...", flush=True)
    limiter = [
        asyncio.run(limiter_burst(args.base_url, "redirect", codes[0], args.redirect_limit, 64)),
        asyncio.run(limiter_burst(args.base_url, "api", codes[0], args.api_limit, 64)),
    ]

    integrity = None
    if args.verify_db_url:
        print("integrity: waiting for batched click writes ...", flush=True)
        expected_urls = len(codes) + create["status_counts"].get("201", 0) + limiter[1]["allowed"]
        expected_clicks = warm_redirects + redirect["status_counts"].get("307", 0) + limiter[0]["allowed"]
        after = asyncio.run(wait_for_clicks(args.verify_db_url, before["click_rows"] + expected_clicks))
        delta = {k: after[k] - before[k] for k in after}
        integrity = {
            "expected_new_url_rows": expected_urls,
            "new_url_rows": delta["url_rows"],
            "duplicate_short_codes": after["url_rows"] - after["distinct_short_codes"],
            "expected_new_click_rows": expected_clicks,
            "new_click_rows": delta["click_rows"],
            "click_counter_increase": delta["click_counter_sum"],
            "urls_consistent": delta["url_rows"] == expected_urls and after["url_rows"] == after["distinct_short_codes"],
            "clicks_consistent": delta["click_rows"] == expected_clicks == delta["click_counter_sum"],
        }

    result = {
        "benchmark": "octoscale-load-test",
        "version": 1,
        "started_at_utc": started_at,
        "git_commit": git_commit(),
        "command": "python " + " ".join(sys.argv),
        "config": {
            "duration_s": args.duration,
            "create_duration_s": args.create_duration,
            "concurrency": args.concurrency,
            "processes": args.processes,
            "simulated_clients": args.clients,
            "setup_urls": args.urls,
            "client_keepalive_expiry_s": KEEPALIVE_EXPIRY_S,
            "client_timeout_s": 10.0,
        },
        "environment": environment(args, health, redis_version),
        "scenarios": {"redirect": redirect, "create": create},
        "rate_limiter": limiter,
        "data_integrity": integrity,
    }
    os.makedirs(os.path.dirname(args.output) or ".", exist_ok=True)
    with open(args.output, "w", encoding="utf-8") as f:
        json.dump(result, f, indent=2)
        f.write("\n")

    for name, s in result["scenarios"].items():
        lat = s["latency_ms"]
        print(f"{name:9} {s['requests_per_second']:>9} req/s  p50 {lat['p50_ms']} ms  p95 {lat['p95_ms']} ms  "
              f"p99 {lat['p99_ms']} ms  errors {s['error_rate']:.4%}")
    for lim in limiter:
        print(f"limiter   {lim['route']:8} limit {lim['limit_per_window']}  allowed {lim['allowed']}  429 {lim['rejected_429']}  exact={lim['exact']}")
    if integrity:
        print(f"integrity urls {integrity['new_url_rows']}/{integrity['expected_new_url_rows']}  "
              f"clicks {integrity['new_click_rows']}/{integrity['expected_new_click_rows']}  "
              f"dupes {integrity['duplicate_short_codes']}  ok={integrity['urls_consistent'] and integrity['clicks_consistent']}")
    print(f"wrote {args.output}")


if __name__ == "__main__":
    main()
